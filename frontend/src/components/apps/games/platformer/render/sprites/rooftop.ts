// Pixel art as data: one character per pixel, '.' is clear, every other
// character is a palette key. Authored with a scratch generator, then
// committed as plain grids: edit the rows here directly.
//
// World 1, neon rooftops at night. Tiles are 16 x 16 and drawn in their lit
// colours (a lighter top edge where the sky light hits); the engine adds the
// darkness and the neon light on top. Each tile kind is one anim whose
// frames are variants (fps 0): pick a variant from the column, for example
// `(col * 7 + row * 3) % frames.length`, so repeated ground does not tile.
// Tile anchor is the top left. Decorations sit on a roof: their anchor is
// the bottom left, so `y` is the top of the tile row they stand on.

// Pixel art as data: one character per pixel, '.' is clear, every other
// character is a palette key. Authored with a scratch generator, then
// committed as plain grids: edit the rows here directly.
//
// The chapter 4 boss, "The Ex-Bestie": a big silverback with a lot of
// attitude, in a red tank top, a gold chain with a banana pendant and white
// wrist sweatbands. Smug, funny, never cruel.
//
// GORILLA: 56 x 56, facing right (the engine mirrors), anchor bottom centre
// (28, 56): the feet stand on row 55. His body fills about x 10 to 48 and
// y 2 to 55 standing (a hit box of about 36 x 50 art px suits). Anims, with
// the fps and loop set in each:
// idle 4 (6 fps, loop): breathing, frame 2 flashes a grin. Smug brow.
// pace 6 (10 fps, loop): the swagger walk, play while he moves.
// chestBeat 4 (8 fps, loop): the taunt and the punish window. Up on his legs,
//   elbows out, drumming: 0 wind up, 1 near fist thump, 2 far fist thump,
//   3 both fists, head back laughing. Loop it for the 1.2 s; show the
//   TAUNT_BUBBLE over his head while it plays.
// throw 4 (10 fps, once): 0 and 1 the wind up with the hands over his head,
//   2 the release (spawn the projectile on this frame), 3 the follow through.
//   GORILLA_THROW_HOLD gives, per frame, the centre of the held thing in
//   sprite px (y may be negative: above the frame); draw the barrel or the
//   debris there on frames 0 and 1, nothing after.
// lunge 3 (10 fps, once): 0 the coil (hold it for the telegraph), 1 the dive
//   (hold while he flies), 2 the skid on landing.
// pound 4 (10 fps, once): 0 both fists high (hold it for the telegraph),
//   1 the swing down, 2 the impact (spawn the shockwaves, shake), 3 the
//   recover grin.
// winded 3 (6 fps, loop): sat on the deck, dizzy stars circling, tongue out.
// climb 4 (8 fps, loop): up a 45 degree cable rising to the right, on all
//   fours. His hands and feet sit on the line y = 66 - x in sprite px, so
//   for these frames place GORILLA_CLIMB_ANCHOR (28, 38), a point on that
//   line, on the cable's walkable top at his x instead of the usual anchor.
//   Mirror for a cable rising to the left.
// slam 3 (10 fps, once): 0 the drop from the cable, fists down (hold while
//   falling), 1 the impact (dust, a spark), 2 back up with a grin.
// hurt 1: the white flash frame (his recoil, all in white with pale lines).
//   Flash it for 2 or 3 frames on a hit, then back to the current anim.
// down 4 (4 fps, once, hold the last): the finish. 0 staggers dizzy, 1 sits
//   down hard, 2 slumps (the last taunt line), 3 sheepish: scratching his
//   head, a sweat drop, a blush, eyes away (the line turns sheepish here).
//
// GORILLA_GLOW lists the keys that glow: r the chain's glint, z A the dizzy
// stars, K the thump sparks, W the hurt flash.
//
// Projectiles share BOSS_PROPS_PALETTE (glow keys in BOSS_PROPS_GLOW):
// BARREL 16 x 16, anchor bottom centre, roll 4 (12 fps, loop): its end
//   rolling, an iron rim and strap; it reads as turning to the right, so
//   mirror it when it rolls left.
// DEBRIS 16 x 16, anchor centre (8, 8), idle 2 frames that are variants
//   (fps 0): 0 a chunk of concrete with rebar, 1 a traffic cone. Pick by
//   the projectile's index; spin it if you like.
// SHOCKWAVE 32 x 8, anchor bottom centre on the deck, roll 3 (12 fps,
//   loop): a breaking curl of dust running right with sparks; mirror for the
//   wave running left.
// WARN_MARK 16 x 8, anchor bottom centre on the deck top, blink 2 (8 fps,
//   loop): a red ring in light and a drop arrow where debris will land; show
//   while the projectile's warn > 0.
// TAUNT_BUBBLE: a 9 slice speech bubble. slice is 12 x 12 with inset 4:
//   the 4 x 4 corners as they are, the middle 4 px of each edge stretched or
//   tiled, the centre plain paper. tail (7 x 5) hangs under the bottom edge:
//   draw it with its top row on the bubble's second to last row, its x
//   anywhere along the bottom edge, so it points down at him. Text in ink,
//   padding 5 px; the 3 x 5 pixel font fits a 16 px tall bubble.

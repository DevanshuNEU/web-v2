/**
 * World 1, neon rooftops at night, as hand-made chunks. The generator
 * (../generate.ts) strings a fixed intro, 6 to 8 of these along a rising
 * difficulty curve, and a fixed finale with the goal beacon.
 *
 * Every chunk is 14 rows, 20 to 30 columns. Its first two columns stand on
 * a roof at `entry` (the row of the roof surface) and its last two on a roof
 * at `exit`, so chunks join where the heights match (the generator puts a
 * short stair bridge between them where they do not). `requires` lists the
 * moves a player needs to get across; tests prove each tag with the
 * reachability check.
 *
 * Legend: the level legend (see ../levels.ts), plus slots the generator
 * fills by seed:
 *   *  optional coin; each horizontal run of them is on or off together
 *   ?  pickup slot: one per level gets the Aura Mode orb
 *   $  Sigma coin slot: at most one per world, about a quarter of runs
 *   %  cracked wall in front of a hidden bonus room (a solid wall when the room is off)
 *   &  bonus room coin (empty when the room is off)
 *   D  optional drone: on in a Drone Swarm, now and then otherwise
 */

export type Move = 'jump' | 'dash' | 'wallJump';

export interface Chunk {
  id: string;
  name: string;
  difficulty: 1 | 2 | 3 | 4 | 5;
  /** Row of the roof surface under the first two columns. */
  entry: number;
  /** Row of the roof surface under the last two columns. */
  exit: number;
  requires: readonly Move[];
  rows: readonly string[];
}

